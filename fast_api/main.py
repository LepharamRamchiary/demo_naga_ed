import logging

from fastapi import FastAPI, HTTPException, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from config import ALLOWED_ORIGINS
from groq_client import GroqAPIError, generate_username_suggestions
from schemas import ErrorResponse, UsernameSuggestionRequest, UsernameSuggestionResponse

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("uvicorn.error")

app = FastAPI(
    title="AI Username Suggestion Service",
    description=(
        "A standalone FastAPI microservice that generates creative username "
        "suggestions from a list of user interests, powered by the Groq LLM API."
    ),
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS or ["*"],
    allow_credentials=True,
    allow_methods=["POST", "GET", "OPTIONS"],
    allow_headers=["*"],
)


@app.get("/", tags=["Health"], summary="Health check")
def health_check():
    """Simple health check endpoint to confirm the service is running."""
    return {"success": True, "message": "AI microservice is running"}


@app.post(
    "/api/suggest-username",
    response_model=UsernameSuggestionResponse,
    responses={
        422: {"model": ErrorResponse, "description": "Malformed input"},
        502: {"model": ErrorResponse, "description": "Groq API call failed"},
    },
    tags=["Username Suggestions"],
    summary="Suggest 3 creative usernames based on interests",
)
async def suggest_username(payload: UsernameSuggestionRequest):
    """
    Accepts a list of user interests and returns 3 unique, creative
    username suggestions generated by an LLM via the Groq API.
    """
    try:
        suggestions = await generate_username_suggestions(payload.interests)
    except GroqAPIError as exc:
        logger.error("Groq API error: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=str(exc),
        ) from exc
    except Exception as exc: 
        logger.exception("Unexpected error generating username suggestions")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Something went wrong while generating suggestions.",
        ) from exc

    return UsernameSuggestionResponse(suggestions=suggestions)


@app.exception_handler(HTTPException)
async def http_exception_handler(_request: Request, exc: HTTPException):
    return JSONResponse(
        status_code=exc.status_code,
        content=ErrorResponse(message=str(exc.detail)).model_dump(),
        headers=exc.headers,
    )


@app.exception_handler(RequestValidationError)
async def request_validation_exception_handler(
    _request: Request, exc: RequestValidationError
):
    messages = "; ".join(error["msg"] for error in exc.errors())
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=ErrorResponse(message=messages).model_dump(),
    )